#!/bin/sh
set -e

# Применяем миграции Alembic перед стартом приложения. Схема БД управляется
# только здесь — приложение в рантайме таблицы не создаёт и не меняет
# (`create_all` из lifespan убран, чтобы не было дрейфа схемы).
# `upgrade head` идемпотентен: если миграции уже применены — это быстрый no-op.
alembic upgrade head

# Запускаем переданную команду (CMD образа — uvicorn). Для bot-сервиса этот
# entrypoint не задаётся — бот миграции не гоняет.
exec "$@"
