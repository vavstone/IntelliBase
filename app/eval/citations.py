"""Маркеры цитат в ответах RAG — для офлайн-оценки (без зависимости от ragas).

Ответы RAG содержат маркеры источников: `[1]` в сыром виде от LLM, `[1 — file.pdf]`
после `parse_citations`. Для метрик, которые судят СОДЕРЖАНИЕ ответа
(faithfulness, answer_relevancy), маркеры утверждениями не являются: генератор
утверждений RAGAS разбирает `[1 — file.pdf]` в отдельное утверждение вида
«…ссылается на документ file.pdf», судья NLI отмечает его неподтверждённым (имени
файла в тексте контекста нет) — и корректный ответ с одной цитатой получает ровно
0.5 вместо 1.0. Метрика `has_citation` считается по исходному ответу.

Модуль намеренно не импортирует ragas: его тестирует обычный прогон pytest.
"""

import re

# [1] и [1 — file.pdf]. Индекс источника — 1..top_k (≤ 10), поэтому цифр не
# больше двух: обычные числа в скобках (`[2026]`) под шаблон не попадают.
CITATION_RE = re.compile(r"\s*\[\d{1,2}(?:\s*[—–-]\s*[^\]]+)?\]")


def strip_citations(text: str) -> str:
    """Убирает маркеры цитат вместе с пробелом перед ними."""
    return CITATION_RE.sub("", text).strip()
